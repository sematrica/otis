"""Filesystem layout of the engine's data directory.

All files the engine creates live under one directory so that nothing is
written to uncontrolled temporary locations:

    <data_dir>/
        verbatim.sqlite3          database (WAL mode)
        work/<job_id>/            per-job working files (extracted audio)
        models/                   default model storage (configurable)
        logs/engine.log
"""

from __future__ import annotations

import os
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

APP_DIR_NAME = "Verbatim"


def default_data_dir() -> Path:
    override = os.environ.get("VERBATIM_DATA_DIR")
    if override:
        return Path(override).expanduser()
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / APP_DIR_NAME
    xdg = os.environ.get("XDG_DATA_HOME")
    base = Path(xdg) if xdg else Path.home() / ".local" / "share"
    return base / APP_DIR_NAME.lower()


@dataclass(frozen=True)
class EnginePaths:
    data_dir: Path

    @classmethod
    def create(cls, data_dir: Path | str | None = None) -> "EnginePaths":
        paths = cls(Path(data_dir).expanduser().resolve() if data_dir else default_data_dir().resolve())
        for directory in (paths.data_dir, paths.work_root, paths.logs_dir):
            directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        return paths

    @property
    def db_path(self) -> Path:
        return self.data_dir / "verbatim.sqlite3"

    @property
    def work_root(self) -> Path:
        return self.data_dir / "work"

    @property
    def logs_dir(self) -> Path:
        return self.data_dir / "logs"

    @property
    def default_models_dir(self) -> Path:
        return self.data_dir / "models"

    def job_dir(self, job_id: str) -> Path:
        # job ids are generated by the engine (uuid4 hex); reject anything else so
        # a crafted id can never escape the work directory.
        if not job_id or not all(c in "0123456789abcdef" for c in job_id):
            raise ValueError(f"invalid job id: {job_id!r}")
        return self.work_root / job_id

    def remove_job_dir(self, job_id: str) -> None:
        directory = self.job_dir(job_id)
        if directory.exists():
            shutil.rmtree(directory, ignore_errors=True)
